bool decode_zero_history(const uint8_t* src, size_t src_len, int mode, uint8_t* dst, size_t dst_len, std::string* why) {
    t_zero_history = true;
    const bool ok = decode(src, src_len, mode, dst, dst_len, why);
    t_zero_history = false;
    return ok;
}
