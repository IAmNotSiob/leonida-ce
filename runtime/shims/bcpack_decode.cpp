// BC1 / BC3 / BC4 / BC5 (strict: confirmed built-in history only)

int bc_delta_1(int v) { return (v & 1) ? 256 - ((v + 1) >> 1) : (v >> 1); }

void bc1_blocks(const Lanes& ln, size_t nb, uint8_t* out) {
    if (any_nonzero(ln[1])) fail("BC1 lane 1 is non-zero (unexpected)");
    static const int mods[6] = {32, 64, 32, 32, 64, 32};
    std::vector<int> hist(nb * 6);
    for (size_t i = 0; i < nb; ++i) {
        const int d = bc_delta_1(ln[0][i]);
        int base[6] = {0, 0, 0, 0, 0, 0};
        if (d == 0) {
        } else if (static_cast<int64_t>(i) - d >= 0) {
            for (int k = 0; k < 6; ++k) base[k] = hist[(i - d) * 6 + k];
        } else {
            const int entry = 256 + static_cast<int>(i) - d;
            if (kBC1Hist[entry * 6] < 0) fail("BC1 block " + std::to_string(i) + " references unconfirmed/unknown built-in history entry " + std::to_string(entry));
            for (int k = 0; k < 6; ++k) base[k] = kBC1Hist[entry * 6 + k];
        }
        int e[6];
        for (int k = 0; k < 6; ++k) e[k] = pymod(base[k] + unzig(ln[2 + k][i]), mods[k]);
        for (int k = 0; k < 6; ++k) hist[i * 6 + k] = e[k];
        const unsigned c0 = (e[0] << 11) | (e[1] << 5) | e[2];
        const unsigned c1 = (e[3] << 11) | (e[4] << 5) | e[5];
        const int a = kBC1Quadrant[ln[8][i]], b = kBC1Quadrant[ln[9][i]], c = kBC1Quadrant[ln[10][i]], dd = kBC1Quadrant[ln[11][i]];
        uint8_t* o = out + i * 8;
        put16(o, c0);
        put16(o + 2, c1);
        o[4] = static_cast<uint8_t>((a & 15) | ((b & 15) << 4));
        o[5] = static_cast<uint8_t>((a >> 4) | ((b >> 4) << 4));
        o[6] = static_cast<uint8_t>((c & 15) | ((dd & 15) << 4));
        o[7] = static_cast<uint8_t>((c >> 4) | ((dd >> 4) << 4));
    }
}

void bc3_blocks(const Lanes& ln, size_t nb, uint8_t* out) {
    if (any_nonzero(ln[1])) fail("BC3 lane 1 is non-zero (unexpected)");
    static const int mods[8] = {256, 256, 32, 64, 32, 32, 64, 32};
    static const int none[8] = {128, 128, 0, 0, 0, 0, 0, 0};
    std::vector<int> hist(nb * 8);
    for (size_t i = 0; i < nb; ++i) {
        const size_t a = 2 * i, b = 2 * i + 1;
        const int d = unzig(inter8(ln[0][a], ln[0][b])) & 255;
        int base[8];
        if (d == 0) {
            std::memcpy(base, none, sizeof base);
        } else if (static_cast<int64_t>(i) - d >= 0) {
            for (int k = 0; k < 8; ++k) base[k] = hist[(i - d) * 8 + k];
        } else {
            const int entry = 256 + static_cast<int>(i) - d;
            if (kBC3Hist[entry * 8] < 0) fail("BC3 block " + std::to_string(i) + " references unconfirmed/unknown built-in history entry " + std::to_string(entry));
            for (int k = 0; k < 8; ++k) base[k] = kBC3Hist[entry * 8 + k];
        }
        const int dz[8] = {ln[2][a], ln[2][b], ln[7][a], ln[8][a], ln[9][a], ln[7][b], ln[8][b], ln[9][b]};
        int e[8];
        for (int k = 0; k < 8; ++k) e[k] = pymod(base[k] + unzig(dz[k]), mods[k]);
        for (int k = 0; k < 8; ++k) hist[i * 8 + k] = e[k];
        uint64_t bits = 0;
        for (int r = 0; r < 4; ++r) {
            const uint8_t* l = &kBC3AlphaPair[ln[3 + r][a] * 2];
            const uint8_t* rr = &kBC3AlphaPair[ln[3 + r][b] * 2];
            bits |= static_cast<uint64_t>(l[0] | (l[1] << 3) | (rr[0] << 6) | (rr[1] << 9)) << (12 * r);
        }
        uint8_t* o = out + i * 16;
        o[0] = static_cast<uint8_t>(e[0]);
        o[1] = static_cast<uint8_t>(e[1]);
        put48(o + 2, bits);
        put16(o + 8, (e[2] << 11) | (e[3] << 5) | e[4]);
        put16(o + 10, (e[5] << 11) | (e[6] << 5) | e[7]);
        const int qa = kBC3ColourQuadrant[ln[10][a]], qb = kBC3ColourQuadrant[ln[10][b]];
        const int qc = kBC3ColourQuadrant[ln[11][a]], qd = kBC3ColourQuadrant[ln[11][b]];
        o[12] = static_cast<uint8_t>((qa & 15) | ((qb & 15) << 4));
        o[13] = static_cast<uint8_t>((qa >> 4) | ((qb >> 4) << 4));
        o[14] = static_cast<uint8_t>((qc & 15) | ((qd & 15) << 4));
        o[15] = static_cast<uint8_t>((qc >> 4) | ((qd >> 4) << 4));
    }
}

void bc4_blocks(const Lanes& ln, size_t nb, uint8_t* out) {
    if (any_nonzero(ln[1])) fail("BC4 lane 1 is non-zero (unexpected)");
    std::vector<int> hist(nb * 2);
    for (size_t i = 0; i < nb; ++i) {
        const int d = bc_delta_1(ln[0][i]);
        int base[2] = {128, 128};
        if (d == 0) {
        } else if (static_cast<int64_t>(i) - d >= 0) {
            base[0] = hist[(i - d) * 2];
            base[1] = hist[(i - d) * 2 + 1];
        } else {
            const int entry = 256 + static_cast<int>(i) - d;
            if (kBC4Hist[entry * 2] < 0) fail("BC4 block " + std::to_string(i) + " references unconfirmed/unknown built-in history entry " + std::to_string(entry));
            base[0] = kBC4Hist[entry * 2];
            base[1] = kBC4Hist[entry * 2 + 1];
        }
        const int a0 = (base[0] + unzig(ln[2][i])) & 255;
        const int a1 = (base[1] + unzig(ln[3][i])) & 255;
        hist[i * 2] = a0;
        hist[i * 2 + 1] = a1;
        uint64_t bits = 0;
        for (int r = 0; r < 4; ++r) {
            const uint8_t* l = &kBC4Pair[ln[4 + 2 * r][i] * 2];
            const uint8_t* rr = &kBC4Pair[ln[4 + 2 * r + 1][i] * 2];
            bits |= static_cast<uint64_t>(l[0] | (l[1] << 3) | (rr[0] << 6) | (rr[1] << 9)) << (12 * r);
        }
        uint8_t* o = out + i * 8;
        o[0] = static_cast<uint8_t>(a0);
        o[1] = static_cast<uint8_t>(a1);
        put48(o + 2, bits);
    }
}

void bc5_blocks(const Lanes& ln, size_t nb, uint8_t* out) {
    if (any_nonzero(ln[1])) fail("BC5 lane 1 is non-zero (unexpected)");
    std::vector<int> hist(nb * 4);
    for (size_t i = 0; i < nb; ++i) {
        const size_t a = 2 * i, b = 2 * i + 1;
        const int d = unzig(inter8(ln[0][a], ln[0][b])) & 255;
        int base[4] = {128, 128, 128, 128};
        if (d == 0) {
        } else if (static_cast<int64_t>(i) - d >= 0) {
            for (int k = 0; k < 4; ++k) base[k] = hist[(i - d) * 4 + k];
        } else {
            const int entry = 256 + static_cast<int>(i) - d;
            if (kBC5Hist[entry * 4] < 0) fail("BC5 block " + std::to_string(i) + " references unconfirmed/unknown built-in history entry " + std::to_string(entry));
            for (int k = 0; k < 4; ++k) base[k] = kBC5Hist[entry * 4 + k];
        }
        const int e[4] = {(base[0] + unzig(ln[2][a])) & 255, (base[1] + unzig(ln[2][b])) & 255,
                          (base[2] + unzig(ln[3][a])) & 255, (base[3] + unzig(ln[3][b])) & 255};
        for (int k = 0; k < 4; ++k) hist[i * 4 + k] = e[k];
        uint8_t* o = out + i * 16;
        for (int ch = 0; ch < 2; ++ch) {
            uint64_t bits = 0;
            for (int r = 0; r < 4; ++r) {
                const uint8_t* l = &kBC5Pair[ln[4 + 4 * ch + r][a] * 2];
                const uint8_t* rr = &kBC5Pair[ln[4 + 4 * ch + r][b] * 2];
                bits |= static_cast<uint64_t>(l[0] | (l[1] << 3) | (rr[0] << 6) | (rr[1] << 9)) << (12 * r);
            }
            o[8 * ch] = static_cast<uint8_t>(e[2 * ch]);
            o[8 * ch + 1] = static_cast<uint8_t>(e[2 * ch + 1]);
            put48(o + 8 * ch + 2, bits);
        }
    }
}

