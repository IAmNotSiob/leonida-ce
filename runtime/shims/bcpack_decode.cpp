// rANS model (bcpack._Model)
struct Model {
    bool ok = false;
    int w = 0;
    int64_t freq[MAX_WIDTH + 1] = {};
    int64_t base[MAX_WIDTH + 1] = {};

    int64_t lookup(int64_t cf) const {
        int p = w;
        while (p > 0 && cf < base[p]) --p;
        if (p == 0) return 0;
        if (freq[p] == 0) fail("zero frequency in lookup");
        return (int64_t{1} << (p - 1)) + (cf - base[p]) / freq[p];
    }
    int64_t advance(int64_t s, int64_t x) const {
        int p = 0;
        while ((s >> p) != 0) ++p;  // bit_length (s >= 0)
        if (p > w) fail("symbol outside its model");
        int64_t f = freq[p];
        int64_t c = base[p] + f * (s - (p == 0 ? 0 : (int64_t{1} << (p - 1))));
        if (c == 0) { f -= 1; c = 1; }
        return f * (x >> 16) + (x & 0xFFFF) - c;
    }
};

struct Models {
    Model m[(MAX_WIDTH + 1) * 16];
    Models() {
        for (int w = 0; w <= MAX_WIDTH; ++w)
            for (int q = 0; q < 16; ++q) {
                const int32_t off = kProbOffset[w * 16 + q];
                if (off < 0) continue;
                Model& md = m[w * 16 + q];
                md.w = w;
                int64_t acc = 0;
                for (int p = 0; p <= w; ++p) {
                    md.freq[p] = kFreq[off + p];
                    md.base[p] = acc;
                    acc += md.freq[p] * (p == 0 ? 1 : (int64_t{1} << (p - 1)));
                }
                md.ok = acc == 65536;  // Python raises BcpackError for such a table
            }
    }
};
const Model* get_model(int w, int q) {
    static const Models models;
    const Model* m = &models.m[w * 16 + q];
    return m->ok ? m : nullptr;
}

// bcpack._decode_lanes_raw. Returns bytes used; lanes[i] gets nsym symbols each.
size_t decode_lanes_raw(const uint8_t* raw, size_t nraw, const uint8_t* widths, int nl, int64_t nsym,
                        std::vector<std::vector<uint16_t>>& out) {
    enum { HDR0, HDR1, HDR2, PROC };
    constexpr int MAXL = 16;
    int ctrl[MAXL], w[MAXL], q[MAXL], h3[MAXL], flush[MAXL], vz[MAXL];
    int64_t out_rem[MAXL], in_rem[MAXL], p0[MAXL], p1[MAXL];
    bool done[MAXL], full[MAXL], held[MAXL], slotfull[MAXL], stall[MAXL];
    int inbuf[MAXL];
    int64_t sym[MAXL], slotval[MAXL];
    const Model* model[MAXL];
    for (int i = 0; i < nl; ++i) {
        ctrl[i] = HDR0; out_rem[i] = nsym; w[i] = q[i] = h3[i] = flush[i] = vz[i] = 0;
        done[i] = nsym <= 0; full[i] = held[i] = slotfull[i] = stall[i] = false;
        inbuf[i] = 0; sym[i] = slotval[i] = 0; in_rem[i] = p0[i] = p1[i] = 0; model[i] = nullptr;
    }
    out.assign(nl, {});
    for (int i = 0; i < nl; ++i) out[i].reserve(static_cast<size_t>(nsym > 0 ? nsym : 0));
    size_t pos = 0;
    const int64_t L = RANS_L;
    // Safety net against a non-terminating loop (Python has none; every valid stream finishes far below this).
    uint64_t guard = 0;
    const uint64_t guard_max = (static_cast<uint64_t>(nraw) + static_cast<uint64_t>(nsym > 0 ? nsym : 0)) * 64 + 4096;

    auto lane_fail = [&](const char* msg, int lane) {
        fail("lane " + std::to_string(lane) + " (width " + std::to_string(w[lane]) + ", q " + std::to_string(q[lane]) +
             ") at input byte " + std::to_string(pos) + ": " + msg);
    };

    for (;;) {
        if (++guard > guard_max) fail("lane decoder did not terminate");
        bool all_done = true;
        for (int i = 0; i < nl; ++i)
            if (!(done[i] && !slotfull[i])) { all_done = false; break; }
        if (all_done) return pos;

        // Phase 1
        int left = PREFETCH_BUDGET;
        for (int i = 0; i < nl; ++i) {
            if (done[i]) { stall[i] = true; continue; }
            if (held[i] && slotfull[i]) { stall[i] = true; continue; }
            stall[i] = false;
            if (ctrl[i] == PROC) p0[i] = held[i] ? model[i]->advance(sym[i], p1[i]) : p1[i];
            if (!full[i] && (ctrl[i] != PROC || in_rem[i] > 0)) {
                if (left == 0) { stall[i] = true; continue; }
                if (pos >= nraw) lane_fail("input ran out", i);
                inbuf[i] = raw[pos];
                ++pos;
                full[i] = true;
                --left;
            }
            if (held[i]) {
                slotfull[i] = true;
                slotval[i] = sym[i];
                held[i] = false;
            }
        }

        // Phase 2
        for (int i = 0; i < nl; ++i) {
            if (done[i] || stall[i]) continue;
            const int c = ctrl[i];
            if (c == HDR0) {
                if (!full[i]) continue;
                const int h = inbuf[i];
                q[i] = h & 15;
                flush[i] = (h >> 4) & 1;
                h3[i] = (h >> 5) & 1;
                w[i] = widths[i] - (h >> 6);
                full[i] = false;
                ctrl[i] = HDR1;
                vz[i] = 0;
            } else if (c == HDR1) {
                if (!full[i]) continue;
                full[i] = false;
                const int wi = w[i];
                if (!(1 <= wi && wi <= MAX_WIDTH)) lane_fail("symbol width out of range", i);
                const Model* m = get_model(wi, q[i]);
                if (!m) lane_fail("probability table for this width and q is not known", i);
                model[i] = m;
                if (h3[i]) {
                    in_rem[i] = inbuf[i];
                    ctrl[i] = HDR2;
                } else {
                    in_rem[i] = inbuf[i] + 1;
                    ctrl[i] = PROC;
                }
            } else if (c == HDR2) {
                if (!full[i]) continue;
                in_rem[i] = ((int64_t{inbuf[i]} << 8) | (in_rem[i] & 0xFF)) + 257;
                ctrl[i] = PROC;
                full[i] = false;
            } else {
                int64_t st = p0[i];
                if (st < L) {
                    if (in_rem[i] > 0) {
                        if (full[i]) {
                            st = (st * 256) | inbuf[i];
                            in_rem[i] -= 1;
                            full[i] = false;
                            if (in_rem[i] == 0 && flush[i]) {
                                while (st < L && st != 0 && vz[i] < MAX_VIRTUAL_ZEROS) { st *= 256; vz[i] += 1; }
                            }
                        }
                    } else if (flush[i]) {
                        if (st == 0 || vz[i] >= MAX_VIRTUAL_ZEROS) lane_fail("fragment did not end at its home state", i);
                        while (st < L && st != 0 && vz[i] < MAX_VIRTUAL_ZEROS) { st *= 256; vz[i] += 1; }
                    } else {
                        p1[i] = st;
                        if (out_rem[i] > 0) ctrl[i] = HDR0;
                        else done[i] = true;
                        continue;
                    }
                }
                const bool nxt = st > L && out_rem[i] > 0;
                if (nxt) {
                    const int64_t s = model[i]->lookup(st & 0xFFFF);
                    sym[i] = s;
                    out_rem[i] -= 1;
                    if (s >> w[i]) lane_fail("symbol outside its width", i);
                }
                held[i] = nxt;
                p1[i] = st;
                if (in_rem[i] == 0) {
                    if (flush[i]) {
                        if (st == L) {
                            if (out_rem[i] > 0) {
                                ctrl[i] = HDR0;
                                p0[i] = 0;
                                p1[i] = 0;
                            } else {
                                done[i] = true;
                            }
                        } else if (st > L && !nxt) {
                            lane_fail("fragment did not end at its home state", i);
                        }
                    } else if (out_rem[i] == 0 && !nxt) {
                        done[i] = true;
                    } else if (st == L) {
                        lane_fail("fragment did not end at its home state", i);
                    }
                } else if (st == L || (out_rem[i] == 0 && !nxt && st > L)) {
                    lane_fail("fragment did not end at its home state", i);
                }
            }
        }

        // Phase 3
        bool ready = true, anyfull = false;
        for (int i = 0; i < nl; ++i) {
            if (slotfull[i]) anyfull = true;
            else if (!(done[i] && !held[i])) { ready = false; break; }
        }
        if (ready && anyfull) {
            for (int i = 0; i < nl; ++i)
                if (slotfull[i]) {
                    out[i].push_back(static_cast<uint16_t>(slotval[i]));
                    slotfull[i] = false;
                }
        }
        for (int i = 0; i < nl; ++i)
            if (done[i] && held[i] && !slotfull[i]) {
                slotfull[i] = true;
                slotval[i] = sym[i];
                held[i] = false;
            }
    }
}

using Lanes = std::vector<std::vector<uint16_t>>;

inline int unzig(int v) { return (v & 1) ? -((v + 1) >> 1) : (v >> 1); }
inline int inter(int a, int b, int n) {
    int d = 0;
    for (int k = 0; k < n; ++k) d |= (((a >> k) & 1) << (2 * k)) | (((b >> k) & 1) << (2 * k + 1));
    return d;
}
inline int inter8(int a, int b) { return inter(a, b, 4); }
inline int deint0(int s) { return ((s >> 0) & 1) | (((s >> 2) & 1) << 1) | (((s >> 4) & 1) << 2) | (((s >> 6) & 1) << 3); }
inline int deint1(int s) { return ((s >> 1) & 1) | (((s >> 3) & 1) << 1) | (((s >> 5) & 1) << 2) | (((s >> 7) & 1) << 3); }
inline int pymod(int a, int m) { int r = a % m; return r < 0 ? r + m : r; }

bool any_nonzero(const std::vector<uint16_t>& v) {
    for (uint16_t x : v) if (x) return true;
    return false;
}

void put16(uint8_t* p, unsigned v) { p[0] = static_cast<uint8_t>(v); p[1] = static_cast<uint8_t>(v >> 8); }
void put48(uint8_t* p, uint64_t v) { for (int k = 0; k < 6; ++k) p[k] = static_cast<uint8_t>(v >> (8 * k)); }

// 128-bit little-endian accumulator (Python's int.to_bytes(16, "little")).
struct Bits128 {
    uint8_t b[16] = {};
    bool overflow = false;
    void or_bits(uint64_t v, int at) {  // v's bits placed starting at bit `at`
        for (int k = 0; v; ++k, v >>= 1)
            if (v & 1) {
                const int p = at + k;
                if (p >= 128) overflow = true;
                else b[p >> 3] |= static_cast<uint8_t>(1u << (p & 7));
            }
    }
};

